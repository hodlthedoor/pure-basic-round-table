def construction(n):
    base, cycles, text = RAW[n]
    rows = [[int(v) + 1 - base for v in line.split()]
            for line in text.strip().splitlines()]
    cycles = [[v + 1 - base for v in cycle] for cycle in cycles]
    return rows, cycles
