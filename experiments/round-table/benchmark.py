"""Record end-to-end timings and independently verified PureBasic output."""
import json
import statistics
import subprocess
import time
from pathlib import Path

from starters import RAW
from verify import verify

ROOT = Path(__file__).resolve().parent
results = ROOT / 'results'
results.mkdir(exist_ok=True)
measurements = []
for n in range(3, 22):
    durations = []
    for _ in range(5):
        start = time.perf_counter()
        run = subprocess.run([str(ROOT / 'build' / 'generate_probe'), str(n)],
                             check=True, capture_output=True, text=True, timeout=5)
        durations.append((time.perf_counter() - start) * 1000)
        rows = [[int(v) for v in line.split()] for line in run.stdout.splitlines()]
        if not verify(n, rows):
            raise RuntimeError(f'Invalid schedule for {n}')
    measurements.append(dict(people=n, sittings=len(rows), verified=True,
                             method='cyclic starters' if n in RAW else 'projective finite field',
                             median_ms=round(statistics.median(durations), 3),
                             maximum_ms=round(max(durations), 3)))
    if n == 21:
        starters_per_group = 19
        blocks = ['\n'.join(' '.join(f'{person:2d}' for person in row)
                            for row in rows[start:start+starters_per_group])
                  for start in range(0, len(rows), starters_per_group)]
        (results / '21-people.txt').write_text(
            '21 people — 190 sittings — independently verified\n'
            'Generated by the PureBasic feasibility probe. Each row wraps around.\n'
            '10 groups of 19, expanded from the attributed 1980 starting rows.\n\n'
            + ('\n' + '-' * 62 + '\n').join(blocks) + '\n')
(results / 'timings.json').write_text(json.dumps({
    'compiler': 'PureBasic 6.41 Free, C backend, macOS arm64',
    'runs_per_count': 5,
    'measurement': 'Process launch + generation + text output, excluding Python verification',
    'results': measurements,
}, indent=2) + '\n')
for item in measurements:
    print(f"{item['people']:2d}  {item['sittings']:3d} rows  "
          f"{item['median_ms']:7.3f} ms median  {item['method']}  VERIFIED")
